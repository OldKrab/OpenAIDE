import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";

import { RUNTIME, SUBMODULE, adapterRepository, git } from "./adapter-repository-fixture.mjs";

const read = (repo, file) => JSON.parse(readFileSync(path.join(repo, RUNTIME, file), "utf8"));

function moveSubmodule(fixture, commit) {
  const submodule = path.join(fixture.repo, SUBMODULE);
  git(submodule, "fetch", "--quiet", "origin");
  git(submodule, "checkout", "--quiet", "--detach", commit);
  git(fixture.repo, "add", SUBMODULE);
}

test("the runtime manifest names the adapter build and only its dependencies", async (t) => {
  const fixture = adapterRepository(t);

  await fixture.run("adapter-lockfile.mjs", ["--write"]);
  await fixture.run("adapter-lockfile.mjs", ["--check"]);

  const manifest = read(fixture.repo, "package.json");
  assert.deepEqual(manifest.openaideAdapter, { name: "@openaide/fixture-acp", version: "1.0.0", commit: fixture.first });
  assert.deepEqual(manifest.dependencies, {});
  assert.equal(read(fixture.repo, "package-lock.json").name, manifest.name);
});

test("the check fails after the submodule moves until the lockfile is regenerated", async (t) => {
  const fixture = adapterRepository(t);
  await fixture.run("adapter-lockfile.mjs", ["--write"]);
  moveSubmodule(fixture, fixture.commitFork("1.1.0"));

  await assert.rejects(fixture.run("adapter-lockfile.mjs", ["--check"]), /npm run adapters:lock/);
  await fixture.run("adapter-lockfile.mjs", ["--write"]);
  await fixture.run("adapter-lockfile.mjs", ["--check"]);
  assert.equal(read(fixture.repo, "package.json").openaideAdapter.version, "1.1.0");
});

test("the lockfile must lock each fork dependency and never the adapter", async (t) => {
  const fixture = adapterRepository(t);
  const commit = fixture.commitFork("1.1.0", { "left-pad": "1.3.0" });
  moveSubmodule(fixture, commit);
  const manifest = {
    name: "openaide-claude-agent-acp-runtime",
    private: true,
    description: `Generated by npm run adapters:lock from ${SUBMODULE}; do not edit.`,
    openaideAdapter: { name: "@openaide/fixture-acp", version: "1.1.0", commit },
    dependencies: { "left-pad": "1.3.0" },
  };
  writeFileSync(path.join(fixture.repo, RUNTIME, "package.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  // npm is not run: these stand in for the lockfiles it could leave.
  const lock = (packages) => writeFileSync(path.join(fixture.repo, RUNTIME, "package-lock.json"), JSON.stringify({
    name: manifest.name, lockfileVersion: 3,
    packages: { "": { name: manifest.name, dependencies: manifest.dependencies }, ...packages },
  }));

  lock({ "node_modules/left-pad": { version: "1.2.0" } });
  await assert.rejects(fixture.run("adapter-lockfile.mjs", ["--check"]), /does not lock left-pad@1\.3\.0/);
  lock({ "node_modules/left-pad": { version: "1.3.0" }, "node_modules/@openaide/fixture-acp": { version: "1.1.0" } });
  await assert.rejects(fixture.run("adapter-lockfile.mjs", ["--check"]), /installs @openaide\/fixture-acp itself/);
  lock({ "node_modules/left-pad": { version: "1.3.0" } });
  await fixture.run("adapter-lockfile.mjs", ["--check"]);
});
